package com.ebremer.beakgraph.cmdline;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.beust.jcommander.IStringConverter;
import com.beust.jcommander.Parameter;
import com.beust.jcommander.converters.NoConverter;
import com.beust.jcommander.internal.DefaultConverterFactory;
import jakarta.json.Json;
import jakarta.json.JsonArray;
import jakarta.json.JsonObject;
import jakarta.json.JsonReader;
import jakarta.json.JsonString;
import jakarta.json.JsonValue;
import java.io.IOException;
import java.lang.reflect.Constructor;
import java.lang.reflect.Field;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import org.junit.jupiter.api.Test;

/**
 * The native binary ({@code -Pcmdlinenative}) reaches by reflection only what
 * {@code reachability-metadata.json} registers, and JCommander works by
 * reflection: it sets every {@code @Parameter} field of {@link Parameters}
 * and builds each validator and converter from its class. The metadata is
 * generated by a tracing run (README, "Building"), and only building the
 * binary showed that it had fallen behind the options: seven fields and three
 * classes were missing, and the binary died before it could print its
 * version. This holds the metadata to the options as they are declared.
 */
class NativeImageMetadataDriftTest {

    private static final Path METADATA = Path.of("src/main/resources/META-INF/native-image/reachability-metadata.json");
    private static final String REGENERATE = " - regenerate the native-image metadata (README, \"Building\")";

    /** The reflection entries by class name. A proxy's entry has no name, and none is ours. */
    private static Map<String, JsonObject> reflection() throws IOException {
        Map<String, JsonObject> byType = new LinkedHashMap<>();
        try (JsonReader in = Json.createReader(Files.newBufferedReader(METADATA, StandardCharsets.UTF_8))) {
            for (JsonValue v : in.readObject().getJsonArray("reflection")) {
                JsonObject entry = v.asJsonObject();
                if (entry.get("type") instanceof JsonString type) byType.put(type.getString(), entry);
            }
        }
        return byType;
    }

    private static List<Field> options() {
        List<Field> options = new ArrayList<>();
        for (Field f : Parameters.class.getDeclaredFields()) {
            if (f.isAnnotationPresent(Parameter.class)) options.add(f);
        }
        assertTrue(options.size() > 20, "the options of the command line: " + options.size());
        return options;
    }

    @Test
    void everyOptionFieldIsRegistered() throws IOException {
        JsonObject entry = reflection().get(Parameters.class.getName());
        assertNotNull(entry, Parameters.class.getName() + " is not registered" + REGENERATE);
        Set<String> registered = new LinkedHashSet<>();
        JsonArray fields = entry.getJsonArray("fields");
        if (fields != null) {
            for (JsonValue f : fields) registered.add(f.asJsonObject().getString("name"));
        }
        List<String> missing = new ArrayList<>();
        for (Field f : options()) {
            if (!registered.contains(f.getName())) missing.add(f.getName());
        }
        assertEquals(List.of(), missing, "option fields the native binary cannot set" + REGENERATE);
    }

    /** What JCommander calls: a converter's (String) constructor if it has one, otherwise the no-argument one. */
    private static List<String> constructorCalled(Class<?> c) {
        if (IStringConverter.class.isAssignableFrom(c)) {
            for (Constructor<?> k : c.getDeclaredConstructors()) {
                if (k.getParameterCount() == 1 && k.getParameterTypes()[0] == String.class) {
                    return List.of(String.class.getName());
                }
            }
        }
        return List.of();
    }

    private static boolean registers(JsonObject entry, List<String> constructor) {
        if (entry == null) return false;
        if (entry.getBoolean("allDeclaredConstructors", false)) return true;
        JsonArray methods = entry.getJsonArray("methods");
        if (methods == null) return false;
        for (JsonValue v : methods) {
            JsonObject m = v.asJsonObject();
            List<String> parameterTypes = new ArrayList<>();
            for (JsonString t : m.getJsonArray("parameterTypes").getValuesAs(JsonString.class)) {
                parameterTypes.add(t.getString());
            }
            if (m.getString("name").equals("<init>") && parameterTypes.equals(constructor)) return true;
        }
        return false;
    }

    @Test
    void everyValidatorAndConverterCanBeBuilt() throws IOException {
        Set<Class<?>> built = new LinkedHashSet<>();
        for (Field f : options()) {
            Parameter p = f.getAnnotation(Parameter.class);
            built.addAll(List.of(p.validateWith()));
            built.addAll(List.of(p.validateValueWith()));
            // An option without a converter of its own gets JCommander's for the field's type.
            Class<?> converter = (p.converter() != NoConverter.class)
                    ? p.converter()
                    : new DefaultConverterFactory().getConverter(f.getType());
            if (converter != null) built.add(converter);
        }
        Map<String, JsonObject> reflection = reflection();
        List<String> missing = new ArrayList<>();
        for (Class<?> c : built) {
            if (!registers(reflection.get(c.getName()), constructorCalled(c))) missing.add(c.getName());
        }
        assertEquals(List.of(), missing, "validators and converters the native binary cannot build" + REGENERATE);
    }
}
